package com.preetTractor.galaxyAndroid.data.UserAccessManagementModel;

public class DynamicData {
    private int id;
    private String client_id;
    private String application_id;
    private String module_name;
    private String field_name;
    private String field_value;
    private String data_option;
    private String data_type;
    private int status;

    public int getId() { return id; }
    public String getClientId() { return client_id; }
    public String getApplicationId() { return application_id; }
    public String getModuleName() { return module_name; }
    public String getFieldName() { return field_name; }
    public String getFieldValue() { return field_value; }
    public String getDataOption() { return data_option; }
    public String getDataType() { return data_type; }
    public int getStatus() { return status; }
}
